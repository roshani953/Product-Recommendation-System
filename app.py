def recommend_for_user(user_id, top_n=5):

    user_id = str(user_id).strip()

    # Get user's rated products
    user_ratings = ratings[
        ratings['UserId'] == user_id
    ]

    if user_ratings.empty:
        return pd.DataFrame()

    # Select highest-rated products as seed items
    user_ratings = user_ratings.sort_values(
        'Rating',
        ascending=False
    ).head(20)

    rated_products = set(
        user_ratings['ProductId']
    )

    scores = {}
    weights = {}

    # Find similar products for each rated item
    for _, row in user_ratings.iterrows():

        product_id = row['ProductId']
        user_rating = row['Rating']

        idx = product_index[product_id]

        n = min(11, len(products))

        distances, indices = model.kneighbors(
            item_matrix.getrow(idx),
            n_neighbors=n
        )

        for distance, neighbour_idx in zip(
            distances[0], indices[0]
        ):

            candidate = str(products[neighbour_idx])

            similarity = max(
                0, 1 - float(distance)
            )

            # Exclude already rated products
            if candidate in rated_products:
                continue

            if similarity <= 0:
                continue

            scores[candidate] = (
                scores.get(candidate, 0)
                + similarity * user_rating
            )

            weights[candidate] = (
                weights.get(candidate, 0)
                + similarity
            )

    if not scores:
        return pd.DataFrame()

    # Calculate weighted recommendation scores
    results = []

    for product_id in scores:

        results.append({
            'ProductId': product_id,
            'Recommendation Score':
                scores[product_id] / weights[product_id]
        })

    result_df = pd.DataFrame(results)

    result_df = result_df.sort_values(
        'Recommendation Score',
        ascending=False
    ).head(top_n)

    # Add product rating information
    result_df = result_df.merge(
        product_stats,
        on='ProductId',
        how='left'
    )

    return result_df


