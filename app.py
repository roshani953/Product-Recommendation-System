# 4. ITEM-TO-ITEM RECOMMENDATION FUNCTION
# ==================================================

def similar_products(product_id, top_n=5):

    product_id = str(product_id).strip()

    if product_id not in product_index:
        return pd.DataFrame()

    idx = product_index[product_id]

    n = min(top_n + 1, len(products))

    distances, indices = model.kneighbors(
        item_matrix.getrow(idx),
        n_neighbors=n
    )

    results = []

    for distance, neighbour_idx in zip(
        distances[0], indices[0]
    ):

        recommended_id = str(products[neighbour_idx])

        # Exclude the original product
        if recommended_id == product_id:
            continue

        similarity = max(0, 1 - float(distance))

        results.append({
            'ProductId': recommended_id,
            'Similarity': similarity
        })

    result_df = pd.DataFrame(results)

    if result_df.empty:
        return result_df

    result_df = result_df.merge(
        product_stats,
        on='ProductId',
        how='left'
    )

    return result_df.head(top_n)


